class bmQ2_Check_Positive_Negative_or_Zero {
    public static void main(String[] args) {
        int n = 10;
        if(n > 0) {
            System.out.println(n + "is positive number.");
        } else if(n < 0) {
            System.out.println(n + "is negative number.");
        } else if(n == 0) {
            System.out.println(n + "the number is zero.");
        }
    }
}