// Q23. Find Percentage

// Question:
// Marks Obtained = 450

// Total Marks = 500

// Final Answer:
// Percentage = 90%

class bmQ23_Find_percentage {
    public static void main(String args[]) {
        int total = 500;
        int obtained = 450;
        System.out.print((obtained * 100.0) / total + " %.");
    }
}